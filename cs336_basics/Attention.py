# 导入 PyTorch。PyTorch 是深度学习框架，torch 是它最常用的包名。
# 后面所有 torch.xxx 都是调用 PyTorch 里的函数。
import torch

# 【注】这个文件是"能直接运行的演示脚本"，不是可复用的模块：
# 全部逻辑都在 main() 里，`python cs336_basics/Attention.py` 会打印两组梯度，
# 而 `import cs336_basics.Attention` 什么都不会执行（不留副作用）。
# 早先这些代码是直接摊在模块层的，import 一次就顺手跑一遍实验，
# 在包里被别的文件误 import 时会莫名其妙多出两行输出。

# ============================================================
# 第一组：较小的 logits（未归一化的得分）
# ============================================================
# torch.tensor([2.0, 1.0, 0.0]) 创建一个一维张量，里面有 3 个浮点数。
# 你可以把它理解成“3 个类别的原始得分”。
# requires_grad=True 表示：请 PyTorch 追踪这个张量上的计算，
# 以后反向传播时要计算“最终结果对它的梯度”。
# 因为 2.0、1.0、0.0 是浮点数，所以默认 dtype 是 float32。

def main():
    # 只是演示：把两段 logits 过一遍 softmax，再看梯度的量级差异
    z_small = torch.tensor([2.0, 1.0, 0.0], requires_grad=True)

    # ============================================================
    # 第二组：较大的 logits（数值差距很大）
    # ============================================================
    # 这里三个得分是 50、20、0。
    # 50 远远大于 20 和 0，所以 Softmax 后第一个类别的概率会非常接近 1，
    # 另外两个类别概率会非常接近 0。
    # requires_grad=True 同样表示要追踪梯度。
    z_large = torch.tensor([50.0, 20.0, 0.0], requires_grad=True)

    # ============================================================
    # 对第一组得分做 Softmax
    # ============================================================
    # torch.softmax(z_small, dim=0) 的作用：
    # 把 z_small 里的 3 个得分变成 3 个概率，使它们都在 0 到 1 之间，
    # 并且三个概率加起来等于 1。
    # dim=0 表示沿着第 0 维做 Softmax。
    # 因为 z_small 是一维张量，所以第 0 维就是它唯一的那一维。
    #
    # Softmax 公式：
    # p_i = exp(z_i) / (exp(z_0) + exp(z_1) + ... )
    #
    # 对 [2.0, 1.0, 0.0] 来说，结果大约是：
    # p_small ≈ [0.6652, 0.2447, 0.0900]
    # 三个数加起来约等于 1。
    p_small = torch.softmax(z_small, dim=0)

    # ============================================================
    # 对第二组得分做 Softmax
    # ============================================================
    # 对 [50.0, 20.0, 0.0] 做 Softmax 后，
    # 第一个概率会非常接近 1，后两个非常接近 0。
    # 结果大约接近 one-hot 形式：[1.0, 0.0, 0.0]。
    # 这就是常说的“Softmax 饱和”。
    p_large = torch.softmax(z_large, dim=0)

    # ============================================================
    # 对第一组结果中的第 0 个概率做反向传播
    # ============================================================
    # p_small 是一个长度为 3 的向量。
    # p_small[0] 取出第 0 个元素，也就是第一个类别的概率。
    # 注意：p_small[0] 是一个“标量张量”，也就是只有一个数。
    #
    # .backward() 表示从 p_small[0] 开始反向传播，
    # 沿着计算图往回算：
    #   z_small -> softmax -> p_small -> p_small[0]
    # 最终计算的是：
    #   ∂p_small[0] / ∂z_small
    # 也就是“第一个类别的概率”分别对 z_small 三个分量的偏导数。
    #
    # 因为 p_small[0] 是标量，所以 backward() 不需要额外传入 gradient 参数。
    # 如果直接对 p_small 这个向量调用 backward()，就需要传一个同形状的梯度。
    p_small[0].backward()

    # 反向传播完成后，梯度会保存在叶子张量 z_small 的 .grad 属性里。
    # z_small.grad 现在是一个长度为 3 的张量，表示：
    # [∂p_small[0]/∂z_small[0],
    #  ∂p_small[0]/∂z_small[1],
    #  ∂p_small[0]/∂z_small[2]]
    #
    # .clone() 是复制一份梯度值。
    # 这样做是为了把当前梯度“保存下来”，避免后面如果梯度被修改或清空，
    # 影响我们保存的 grad_small。
    grad_small = z_small.grad.clone()

    # ============================================================
    # 清空第二组张量的梯度
    # ============================================================
    # PyTorch 的 .grad 默认是“累加”的。
    # 如果你对同一个张量多次 backward()，梯度会不断加到 .grad 上。
    # 所以实际训练中，每轮反向传播前通常要清空梯度。
    #
    # 这里把 z_large.grad 设为 None，表示当前没有梯度。
    # 因为 z_large 还没做过 backward()，它原本的 grad 本来也是 None，
    # 这里这样写主要是演示“清空梯度”的习惯。
    z_large.grad = None

    # ============================================================
    # 对第二组结果中的第 0 个概率做反向传播
    # ============================================================
    # p_large[0] 也是标量，表示大数值 Softmax 后第一个类别的概率。
    # 对它调用 backward()，计算：
    #   ∂p_large[0] / ∂z_large
    # 结果会保存到 z_large.grad 中。
    p_large[0].backward()

    # 取出 z_large 的梯度。
    # 这里没有再 clone，因为后面不再修改它，直接引用也可以。
    # 为了更安全，你也可以写成 z_large.grad.clone()。
    grad_large = z_large.grad

    # ============================================================
    # 打印第一组梯度
    # ============================================================
    # f-string 是 Python 的格式化字符串，f"..." 里面可以用 {变量名} 插入变量。
    # grad_small 大约会是：
    # [0.2227, -0.1628, -0.0599]
    # 这说明梯度还比较“活跃”，不是 0。
    print(f"小数值下的梯度: {grad_small}") 
    # 输出示意: [ 0.22, -0.16, -0.06] -> 梯度很活跃

    # ============================================================
    # 打印第二组梯度
    # ============================================================
    # grad_large 会非常接近 0。
    # 在 float32 下，Softmax([50,20,0]) 的第 0 个概率会被舍入成 1.0，
    # 所以 ∂p_0/∂z_0 = p_0(1-p_0) 可能直接变成 0。
    # 另外两个梯度也极其小，打印出来通常显示为 0.00。
    print(f"大数值(One-hot)下的梯度: {grad_large}")  
    # 输出示意: [ 0.00,  0.00,  0.00] -> 梯度死了！


if __name__ == "__main__":
    main()
